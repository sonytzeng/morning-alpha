// Extract the read-only verifier; never bundle the research evaluator in the UI.
import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';
import {createHash} from 'node:crypto';
import ts from 'typescript';

const root=new URL('../../',import.meta.url);
export const browserLockPath='src/features/vnext/browserDailyLock.ts';
const read=path=>readFileSync(new URL(path,root),'utf8');
function declarations(path,names){
 const source=read(path),ast=ts.createSourceFile(path,source,ts.ScriptTarget.Latest,true),wanted=new Set(names),found=[];
 for(const node of ast.statements){
  const name=ts.isFunctionDeclaration(node)?node.name?.text:ts.isVariableStatement(node)&&node.declarationList.declarations.length===1
   ?node.declarationList.declarations[0].name.getText(ast):null;
  if(wanted.delete(name))found.push(node.getText(ast));
 }
 if(wanted.size)throw Error('BROWSER_LOCK_DECLARATION_MISSING:'+path+':'+[...wanted].join(','));
 return found.join('\n');
}
export function renderBrowserDailyLock(){
 const daily='src/features/vnext/dailyIntelligence.ts',entry='research/entry-opportunity.ts',funnel='src/features/vnext/researchFunnel.ts',
  calendar='supabase/functions/_shared/market-session-contract.mjs',data='supabase/functions/_shared/market-calendar-data.json';
 const hashes=[daily,entry,funnel,calendar,data].map(path=>'// '+path+' sha256:'+createHash('sha256').update(read(path)).digest('hex'));
 return [
  '// Generated by scripts/vnext/build-browser-daily-lock.mjs. Do not edit by hand.',
  '// Read-only checks copied from the canonical engine; no evaluation, acquisition or publication.',
  ...hashes,
  "import {HORIZONS,hashValid,snapshotHash,validTime} from './contracts.ts';",
  "import type {DailyLock} from './dailyIntelligence.ts';",
  declarations(funnel,['RESEARCH_FUNNEL_VERSION']),
  declarations(entry,['ENTRY_VERSION','ENTRY_PREMARKET_VERSION','STRATEGIES','ENTRY_POLICY']),
  'const calendar = '+JSON.stringify(JSON.parse(read(data)),null,2)+';',
  declarations(calendar,['coveredCalendarDate','isMarketTradingDate','previousMarketTradingDate']),
  declarations(daily,['day','verifyDailyLock']),
  '',
 ].join('\n');
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 const output=renderBrowserDailyLock(),target=new URL(browserLockPath,root);
 if(process.argv.includes('--check')){
  if(readFileSync(target,'utf8')!==output)throw Error('BROWSER_LOCK_GENERATED_SOURCE_STALE');
 }else writeFileSync(target,output);
}
